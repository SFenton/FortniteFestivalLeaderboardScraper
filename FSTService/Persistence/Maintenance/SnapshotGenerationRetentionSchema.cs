                            'Solo_Bass',
                            'Solo_Vocals',
                            'Solo_Drums',
                            'Solo_PeripheralGuitar',
                            'Solo_PeripheralBass',
                            'Solo_PeripheralVocals',
                            'Solo_PeripheralCymbals',
                            'Solo_PeripheralDrums')),
                CONSTRAINT
                    ck_snapshot_generation_retention_observation_class
                    CHECK (
                        classification IN (
                            'candidate',
                            'protected',
                            'blocked',
                            'oracle_mismatch')),
                CONSTRAINT
                    ck_snapshot_generation_retention_observation_identity
                    CHECK (
                        snapshot_id > 0
                        AND snapshot_parent_oid >= 0
                        AND root_oid >= 0
                        AND child_oid > 0
                        AND child_relfilenode > 0
                        AND row_estimate >= 0
                        AND total_bytes >= 0),
                CONSTRAINT
                    ck_snapshot_generation_retention_observation_hashes
                    CHECK (
                        stable_child_identity_hash
                            ~ '^[0-9a-f]{64}$'
                        AND stable_config_schema_hash
                            ~ '^[0-9a-f]{64}$'
                        AND observation_metrics_hash
                            ~ '^[0-9a-f]{64}$'),
                CONSTRAINT
                    ck_snapshot_generation_retention_observation_names
                    CHECK (
                        root_schema <> ''
                        AND root_relation <> ''
                        AND root_partition_key <> ''
                        AND root_partition_bound <> ''
                        AND root_tablespace_name <> ''
                        AND child_schema <> ''
                        AND child_relation <> ''
                        AND partition_bound <> ''
                        AND tablespace_name <> ''
                        AND relation_kind <> ''
                        AND persistence_kind <> ''
                        AND access_method <> ''),
                CONSTRAINT
                    ck_snapshot_generation_retention_observation_agreement
                    CHECK (
                        classification = 'oracle_mismatch'
                        OR planner_live = oracle_live)
            );

