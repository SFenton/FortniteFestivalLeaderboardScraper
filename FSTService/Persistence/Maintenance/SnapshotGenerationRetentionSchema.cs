        CREATE OR REPLACE FUNCTION
            public.fst_reject_snapshot_generation_retention_evidence_mutation()
        RETURNS trigger
        LANGUAGE plpgsql
        AS $retention_immutable$
        BEGIN
            RAISE EXCEPTION
                'Snapshot-generation retention report evidence is immutable.'
                USING ERRCODE = '55000';
        END
        $retention_immutable$;

        DO $retention_triggers$
        DECLARE
            relation_name TEXT;
            trigger_name TEXT;
        BEGIN
            FOREACH relation_name IN ARRAY ARRAY[
                'snapshot_generation_retention_cycles',
                'snapshot_generation_retention_observations',
                'snapshot_generation_retention_deferrals',
                'snapshot_generation_retention_evidence',
                'snapshot_generation_retention_worker_configuration'
            ]
            LOOP
                trigger_name := CASE
                    WHEN relation_name = 'snapshot_generation_retention_worker_configuration'
                    THEN 'trg_reject_retention_worker_configuration_mutation'
                    ELSE 'trg_reject_' || relation_name || '_mutation'
                END;
                IF NOT EXISTS (
                    SELECT 1
                    FROM pg_catalog.pg_trigger trigger_row
                    WHERE trigger_row.tgrelid =
                            pg_catalog.to_regclass(
                                'public.' || relation_name)
                      AND trigger_row.tgname = trigger_name
                      AND NOT trigger_row.tgisinternal
                ) THEN
                    EXECUTE pg_catalog.format(
                        'CREATE TRIGGER %I BEFORE UPDATE OR DELETE OR TRUNCATE ON public.%I FOR EACH STATEMENT EXECUTE FUNCTION public.fst_reject_snapshot_generation_retention_evidence_mutation()',
                        trigger_name,
                        relation_name);
                END IF;
                IF relation_name = 'snapshot_generation_retention_worker_configuration'
                    AND EXISTS (
                        SELECT 1 FROM pg_catalog.pg_trigger
                        WHERE tgrelid=pg_catalog.to_regclass('public.' || relation_name)
                          AND tgname=pg_catalog.left('trg_reject_' || relation_name || '_mutation',63)
                    )
                THEN
                    EXECUTE pg_catalog.format('DROP TRIGGER %I ON public.%I',
                        pg_catalog.left('trg_reject_' || relation_name || '_mutation',63),relation_name);
                END IF;
            END LOOP;
        END
        $retention_triggers$;
        """;
