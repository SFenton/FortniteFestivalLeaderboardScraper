namespace FSTService.Persistence.Maintenance;

public static class SnapshotGenerationRetentionSchema
{
    public const string Sql = """
        DO $retention_schema_admission$
        DECLARE
            worker_row RECORD;
        BEGIN
            IF NOT pg_catalog.pg_try_advisory_xact_lock(
                pg_catalog.hashtextextended(
                    'fst.snapshot-generation-retention-schema', 0))
            THEN
                RAISE EXCEPTION
                    'Snapshot-generation retention schema admission is busy in this database; retry initialization.'
                    USING ERRCODE = '55P03';
            END IF;
            IF pg_catalog.to_regclass('public.snapshot_generation_retention_cycles') IS NOT NULL
                AND NOT EXISTS (
                    SELECT 1 FROM pg_catalog.pg_constraint
                    WHERE conrelid=pg_catalog.to_regclass('public.snapshot_generation_retention_cycles')
                      AND conname='ux_snapshot_generation_retention_cycle_trigger'
                )
            THEN
                IF NOT pg_catalog.pg_try_advisory_xact_lock(5067481511116518500)
                    OR NOT pg_catalog.pg_try_advisory_xact_lock(2026050901)
                    OR NOT pg_catalog.pg_try_advisory_xact_lock_shared(5067481511116519500)
                    OR NOT pg_catalog.pg_try_advisory_xact_lock(2026082301)
                THEN
                    RAISE EXCEPTION
                        'Canonical retention migration requires quiescent legacy writers; retry after the guarded worker stop.'
                        USING ERRCODE='55P03';
                END IF;
                LOCK TABLE ONLY public.service_worker_status IN SHARE MODE NOWAIT;
                SELECT * INTO worker_row FROM public.service_worker_status
                WHERE worker_key='scraper' FOR SHARE NOWAIT;
                IF FOUND THEN
                    IF worker_row.status IS DISTINCT FROM 'offline'
                        OR worker_row.mode IS DISTINCT FROM 'scraper'
                        OR worker_row.current_operation_json IS NOT NULL
                        OR coalesce(pg_catalog.btrim(worker_row.instance_id),'') = ''
                        OR worker_row.started_at IS NULL
                        OR worker_row.last_status_change_at IS NULL
                        OR worker_row.last_heartbeat_at IS NULL
                        OR worker_row.started_at > worker_row.last_status_change_at
                        OR worker_row.last_status_change_at > worker_row.last_heartbeat_at
                        OR worker_row.last_heartbeat_at > pg_catalog.clock_timestamp()
                        OR worker_row.last_status_change_at < pg_catalog.clock_timestamp() - interval '15 minutes'
                    THEN
                        RAISE EXCEPTION
                            'Canonical retention migration refuses an active, unknown, or stale worker; a fresh guarded offline boundary is required.'
                            USING ERRCODE='55000';
                    END IF;
                ELSIF EXISTS (SELECT 1 FROM public.scrape_log) THEN
                    RAISE EXCEPTION
                        'Canonical retention migration requires authoritative worker identity for an existing scrape database.'
                        USING ERRCODE='55000';
                END IF;
                PERFORM id FROM public.scrape_publication_state WHERE id=TRUE FOR SHARE NOWAIT;
                IF EXISTS (SELECT 1 FROM public.scrape_log WHERE status='running')
                    OR EXISTS (
                        SELECT 1 FROM public.scrape_publication_state
                        WHERE public_reads_frozen OR working_publication_id IS NOT NULL
                          OR publication_commit_intent_started_at IS NOT NULL
                          OR max_score_mutation_gate_token IS NOT NULL
                    )
                THEN
                    RAISE EXCEPTION
                        'Canonical retention migration requires completed, unfrozen publication state.'
                        USING ERRCODE='55000';
                END IF;
            END IF;
        END
        $retention_schema_admission$;

        CREATE TABLE IF NOT EXISTS public.snapshot_generation_retention_cycles (
            cycle_id                   BIGINT GENERATED BY DEFAULT AS IDENTITY
                                       PRIMARY KEY,
            trigger_scrape_id          BIGINT NOT NULL
                                       REFERENCES public.scrape_log(id)
                                       ON DELETE RESTRICT,
            trigger_publication_id     BIGINT NOT NULL
                                       REFERENCES public.publication_generations(
                                           publication_id)
                                       ON DELETE RESTRICT,
            safe_point_kind            TEXT NOT NULL,
            safe_point_at              TIMESTAMPTZ NOT NULL,
            planner_version            INTEGER NOT NULL,
            config_version             INTEGER NOT NULL,
            report_only                BOOLEAN NOT NULL DEFAULT TRUE,
            status                     TEXT NOT NULL,
            oracle_agreement           BOOLEAN NOT NULL,
            candidate_identity_hash    TEXT NOT NULL,
            observation_hash           TEXT NOT NULL,
            planner_child_set          JSONB NOT NULL,
            planner_live_set           JSONB NOT NULL,
            planner_candidate_set      JSONB NOT NULL,
            oracle_child_set           JSONB NOT NULL,
            oracle_live_set            JSONB NOT NULL,
            oracle_candidate_set       JSONB NOT NULL,
            candidate_count            INTEGER NOT NULL,
            protected_count            INTEGER NOT NULL,
            blocked_count              INTEGER NOT NULL,
            candidate_bytes            BIGINT NOT NULL,
            global_blockers            JSONB NOT NULL DEFAULT '[]'::jsonb,
            anomalies                  JSONB NOT NULL DEFAULT '[]'::jsonb,
            error_message              TEXT,
            created_at                 TIMESTAMPTZ NOT NULL
                                       DEFAULT pg_catalog.clock_timestamp(),
            CONSTRAINT
                ux_snapshot_generation_retention_cycle_safe_point
                UNIQUE (
                    trigger_scrape_id,
                    trigger_publication_id,
                    safe_point_kind),
            CONSTRAINT
                ck_snapshot_generation_retention_cycle_safe_point
                CHECK (
                    safe_point_kind IN (
                        'terminal_worker_post_publication',
                        'operator_offline_post_publication')),
            CONSTRAINT
                ck_snapshot_generation_retention_cycle_versions
                CHECK (
                    planner_version > 0
                    AND config_version > 0),
            CONSTRAINT
                ck_snapshot_generation_retention_cycle_report_only
                CHECK (report_only),
            CONSTRAINT
                ck_snapshot_generation_retention_cycle_status
                CHECK (
                    status IN (
                        'observed',
                        'blocked',
                        'oracle_mismatch',
                        'failed')),
            CONSTRAINT
                ck_snapshot_generation_retention_cycle_hashes
                CHECK (
                    candidate_identity_hash ~ '^[0-9a-f]{64}$'
                    AND observation_hash ~ '^[0-9a-f]{64}$'),
            CONSTRAINT
                ck_snapshot_generation_retention_cycle_counts
                CHECK (
                    candidate_count >= 0
                    AND protected_count >= 0
                    AND blocked_count >= 0
                    AND candidate_bytes >= 0),
            CONSTRAINT
                ck_snapshot_generation_retention_cycle_oracle
                CHECK (
                    (status = 'oracle_mismatch'
                        AND NOT oracle_agreement
                        AND candidate_count = 0)
                    OR
                    (status IN ('observed', 'blocked')
                        AND oracle_agreement)
                    OR status = 'failed')
        );

        ALTER TABLE public.snapshot_generation_retention_cycles
            ADD COLUMN IF NOT EXISTS anomalies
                JSONB NOT NULL DEFAULT '[]'::jsonb;

        DO $offline_retention_safe_point$
        BEGIN
            IF NOT EXISTS (
                SELECT 1
                FROM pg_catalog.pg_constraint
                WHERE conrelid =
                        'public.snapshot_generation_retention_cycles'::regclass
                  AND conname =
                        'ck_snapshot_generation_retention_cycle_safe_point'
                  AND pg_catalog.pg_get_expr(conbin, conrelid, false) =
                    '(safe_point_kind = ANY (ARRAY[''terminal_worker_post_publication''::text, ''operator_offline_post_publication''::text]))'
            ) THEN
                ALTER TABLE public.snapshot_generation_retention_cycles
                    DROP CONSTRAINT IF EXISTS
                        ck_snapshot_generation_retention_cycle_safe_point;
                ALTER TABLE public.snapshot_generation_retention_cycles
                    ADD CONSTRAINT
                        ck_snapshot_generation_retention_cycle_safe_point
                    CHECK (
                        safe_point_kind IN (
                            'terminal_worker_post_publication',
                            'operator_offline_post_publication'));
            END IF;
        END
        $offline_retention_safe_point$;

        DO $canonical_retention_cycle$
        BEGIN
            IF EXISTS (
                SELECT 1
                FROM public.snapshot_generation_retention_cycles
                GROUP BY trigger_scrape_id, trigger_publication_id
                HAVING count(*) > 1
            ) THEN
                RAISE EXCEPTION
                    'Duplicate immutable retention cycles require explicit operator adjudication; no evidence was rewritten.'
                    USING ERRCODE = '55000';
            END IF;
            IF NOT EXISTS (
                SELECT 1 FROM pg_catalog.pg_constraint
                WHERE conrelid =
                        'public.snapshot_generation_retention_cycles'::regclass
                  AND conname =
                        'ux_snapshot_generation_retention_cycle_trigger'
            ) THEN
                ALTER TABLE public.snapshot_generation_retention_cycles
                    ADD CONSTRAINT ux_snapshot_generation_retention_cycle_trigger
                    UNIQUE (trigger_scrape_id, trigger_publication_id);
            ELSIF NOT EXISTS (
                SELECT 1 FROM pg_catalog.pg_constraint
                WHERE conrelid =
                        'public.snapshot_generation_retention_cycles'::regclass
                  AND conname =
                        'ux_snapshot_generation_retention_cycle_trigger'
                  AND contype = 'u'
                  AND convalidated
                  AND pg_catalog.pg_get_constraintdef(oid, false) =
                        'UNIQUE (trigger_scrape_id, trigger_publication_id)'
            ) THEN
                RAISE EXCEPTION
                    'The canonical retention-cycle constraint does not match the accepted contract.'
                    USING ERRCODE = '55000';
            END IF;
        END
        $canonical_retention_cycle$;

        CREATE INDEX IF NOT EXISTS
            ix_snapshot_generation_retention_cycles_created
            ON public.snapshot_generation_retention_cycles (
                created_at DESC,
                cycle_id DESC);

        CREATE TABLE IF NOT EXISTS
